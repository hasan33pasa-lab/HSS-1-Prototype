"""Assembler for the separate 16-bit datapath lab profile."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

from .assembler import (
    BINARY_OPS,
    IMMEDIATE_OPS,
    MEMORY_OPS,
    SINGLE_REG_OPS,
    _imm8,
    _literal_number,
    _parse_source,
    _reg,
    encode_instruction_check,
)

OPCODES16 = {
    "NOP": 0x0, "LDI": 0x1, "ADDI": 0x2, "XORI": 0x3,
    "OUT": 0x4, "JMP": 0x5, "JZ": 0x6, "LOAD": 0x7,
    "STORE": 0x8, "ADD": 0x9, "SUB": 0xA, "AND": 0xB,
    "OR": 0xC, "XOR": 0xD, "MOV": 0xE, "HALT": 0xF,
    "LDIH": 0xF,
}


def assemble_text16(text: str) -> list[int]:
    labels, statements = _parse_source(text)
    words: list[int] = []
    for address, line, op, args in statements:
        if op not in OPCODES16:
            raise ValueError(f"Line {line}: unknown instruction {op!r}")
        word = OPCODES16[op] << 12

        if op in {"NOP", "HALT"}:
            if args:
                raise ValueError(f"Line {line}: {op} takes no operands")
        elif op == "LDIH":
            if len(args) != 2:
                raise ValueError(f"Line {line}: LDIH expects register, high-byte immediate")
            destination = _reg(args[0], line)
            high_byte = _imm8(args[1], labels, line)
            word |= destination << 10 | 0x0100 | high_byte
        elif op in IMMEDIATE_OPS:
            if len(args) != 2:
                raise ValueError(f"Line {line}: {op} expects register, unsigned immediate")
            destination = _reg(args[0], line)
            immediate = _imm8(args[1], labels, line)
            word |= destination << 10 | immediate
        elif op in SINGLE_REG_OPS:
            if len(args) != 1:
                raise ValueError(f"Line {line}: {op} expects one register")
            word |= _reg(args[0], line) << 10
        elif op == "JMP":
            if len(args) != 1:
                raise ValueError(f"Line {line}: JMP expects one address or label")
            word |= _imm8(args[0], labels, line)
        elif op == "JZ":
            if len(args) != 2:
                raise ValueError(f"Line {line}: JZ expects register, address or label")
            destination = _reg(args[0], line)
            target = _imm8(args[1], labels, line)
            word |= destination << 10 | target
        elif op in MEMORY_OPS:
            if len(args) != 2:
                raise ValueError(f"Line {line}: {op} expects register, private RAM address")
            destination = _reg(args[0], line)
            memory_address = _literal_number(args[1], line, "private RAM address")
            if not 0 <= memory_address <= 15:
                raise ValueError(f"Line {line}: private RAM address must be 0..15")
            word |= destination << 10 | memory_address
        elif op in BINARY_OPS:
            if len(args) != 2:
                raise ValueError(f"Line {line}: {op} expects two registers")
            destination = _reg(args[0], line)
            source = _reg(args[1], line)
            word |= destination << 10 | source << 8
        else:
            raise ValueError(f"Line {line}: no 16-bit encoder for {op}")
        words.append(word)
    return words


def _module_body(module_name: str, words: Iterable[int]) -> list[str]:
    body = [
        f"module {module_name} (",
        "    input wire [7:0] address,",
        "    output reg [15:0] instruction,",
        "    output reg [5:0] instruction_check",
        ");",
        "    always @* begin",
        "        case (address)",
    ]
    for address, word in enumerate(words):
        body += [
            f"            8'd{address}: begin",
            f"                instruction = 16'h{word:04X};",
            f"                instruction_check = 6'h{encode_instruction_check(word):02X};",
            "            end",
        ]
    halt_check = encode_instruction_check(0xF000)
    body += [
        "            default: begin",
        "                instruction = 16'hF000;",
        f"                instruction_check = 6'h{halt_check:02X};",
        "            end",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    return body


def emit_rom16(main_words: list[int], guard_words: list[int]) -> str:
    lines = ["// Generated by tools/assembler16.py. Do not edit by hand.", ""]
    lines += _module_body("wide16_main_program_rom", main_words)
    lines += _module_body("wide16_guard_program_rom", guard_words)
    return "\n".join(lines)


def assemble_files16(
    main_path: Path,
    guard_path: Path,
    output_path: Path,
    artifact_dir: Path | None = None,
) -> tuple[list[int], list[int]]:
    main_text = main_path.read_text(encoding="utf-8")
    guard_text = guard_path.read_text(encoding="utf-8")
    main_words = assemble_text16(main_text)
    guard_words = assemble_text16(guard_text)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(emit_rom16(main_words, guard_words), encoding="ascii")

    artifacts = artifact_dir if artifact_dir is not None else output_path.parent
    artifacts.mkdir(parents=True, exist_ok=True)
    for name, source, words in (
        ("wide16_main", main_text, main_words),
        ("wide16_guard", guard_text, guard_words),
    ):
        _, statements = _parse_source(source)
        listing = ["ADDR  WORD  SOURCE"]
        for word, (address, line_number, op, operands) in zip(words, statements):
            args = ", ".join(operands)
            listing.append(f"{address:04X}  {word:04X}  L{line_number}: {op} {args}".rstrip())
        (artifacts / f"{name}.lst").write_text("\n".join(listing) + "\n", encoding="utf-8")
        (artifacts / f"{name}.mem").write_text(
            "".join(f"{word:04X}\n" for word in words), encoding="ascii"
        )
    return main_words, guard_words


def main() -> int:
    parser = argparse.ArgumentParser(description="Assemble the 16-bit datapath lab profile")
    parser.add_argument("--main", type=Path, default=Path("programs/wide16_main.asm"))
    parser.add_argument("--guard", type=Path, default=Path("programs/wide16_guard.asm"))
    parser.add_argument("--output", type=Path, default=Path("rtl/wide16_program_rom.v"))
    parser.add_argument("--artifact-dir", type=Path, default=Path("build/generated16"))
    args = parser.parse_args()
    try:
        main_words, guard_words = assemble_files16(args.main, args.guard, args.output, args.artifact_dir)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    print(f"Wide16 Main: {len(main_words)} instructions")
    print(f"Wide16 Guard: {len(guard_words)} instructions")
    print(f"Generated ROM: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
